void main() {
  print("Operaciones Aritméticas en Historias Clínicas");

  final double pesoPaciente = 70.5; 
  double pesoPerdido = 2.0;

  print("Peso inicial: $pesoPaciente kg");
  print("Peso perdido: $pesoPerdido kg");

  print("Peso total después de perder: ${pesoPaciente - pesoPerdido} kg");
  print("Peso total si gana peso: ${pesoPaciente + pesoPerdido} kg");
  print("Multiplicación ejemplo (peso x 2): ${pesoPaciente * 2} kg");
  print("División ejemplo (peso / 2): ${pesoPaciente / 2} kg");
}
